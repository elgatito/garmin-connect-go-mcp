var localOnlyTools = map[string]bool{
	"list_accounts":        true,
	"set_fit_download_dir": true,
}

// annotationsFor returns the explicit effect classification for a tool, or nil
// when the tool is not classified.
func annotationsFor(name string) *mcp.ToolAnnotations {
	switch {
	case readOnlyTools[name]:
		return &mcp.ToolAnnotations{
			ReadOnlyHint:    true,
			DestructiveHint: boolPtr(false),
			OpenWorldHint:   boolPtr(!localOnlyTools[name]),
		}
	case additiveTools[name]:
		return &mcp.ToolAnnotations{
			ReadOnlyHint:    false,
			DestructiveHint: boolPtr(false),
			IdempotentHint:  idempotentTools[name],
			OpenWorldHint:   boolPtr(!localOnlyTools[name]),
		}
	case destructiveTools[name]:
		return &mcp.ToolAnnotations{
			ReadOnlyHint:    false,
			DestructiveHint: boolPtr(true),
			IdempotentHint:  idempotentTools[name],
			OpenWorldHint:   boolPtr(!localOnlyTools[name]),
		}
	default:
		return nil
	}
}

func boolPtr(v bool) *bool { return &v }
